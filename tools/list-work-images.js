/* Rebuilds site/js/work-images.js from the photos in site/images/work-thumb,
   recording each photo's width and height so the gallery can lay out instantly.
   Run after adding photos:  node tools/list-work-images.js
   (make the thumb/large copies first with tools/resize-work-images.ps1) */
const fs = require("fs"), path = require("path");
const dir = path.join(__dirname, "..", "site", "images", "work-thumb");

// read width/height from a JPEG's SOF marker (no extra packages needed)
function jpegSize(file) {
  const b = fs.readFileSync(file);
  let i = 2;
  while (i < b.length) {
    if (b[i] !== 0xff) { i++; continue; }
    const m = b[i + 1], len = b.readUInt16BE(i + 2);
    if (m >= 0xc0 && m <= 0xcf && m !== 0xc4 && m !== 0xc8 && m !== 0xcc) return [b.readUInt16BE(i + 7), b.readUInt16BE(i + 5)];
    i += 2 + len;
  }
  return [4, 3];
}

const files = fs.readdirSync(dir).filter(f => /\.jpe?g$/i.test(f)).sort();
const rows = files.map(f => { const [w, h] = jpegSize(path.join(dir, f)); return `  ["${f}", ${w}, ${h}]`; });
const out = "/* Generated by tools/list-work-images.js — every photo in images/work as [file, width, height] */\n" +
  "window.WORK_IMAGES = [\n" + rows.join(",\n") + "\n];\n";
fs.writeFileSync(path.join(__dirname, "..", "site", "js", "work-images.js"), out);
console.log("listed", files.length, "photos");
